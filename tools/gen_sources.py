#!/usr/bin/env python3
"""Generate cmake/core_sources.cmake from the src/core module tree.

The source list used to be a file(GLOB) in CMakeLists.txt, which silently
picked up new files and made a rebuild depend on directory timestamps.  The
list is generated instead, so adding a file is an explicit diff and --check can
fail a build that forgot to regenerate it.
"""

import argparse
import os
import sys

MODULE_ORDER = ["base", "geom", "numeric", "field", "cover", "param", "extract", "pipeline"]


def collect(root):
    entries = []
    for module in MODULE_ORDER:
        directory = os.path.join(root, "src", "core", module)
        if not os.path.isdir(directory):
            continue
        for name in sorted(os.listdir(directory)):
            if name.endswith(".cpp"):
                entries.append((module, "src/core/%s/%s" % (module, name)))
    return entries


def render(entries):
    lines = [
        "# Generated by tools/gen_sources.py -- do not edit by hand.",
        "# Re-run: python tools/gen_sources.py",
        "set(AUTOREMESHER_CORE_MODULE_SOURCES",
    ]
    for _, relative in entries:
        lines.append('    "' + relative + '"')
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".")
    parser.add_argument("--output", default="cmake/core_sources.cmake")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()

    root = os.path.abspath(arguments.root)
    entries = collect(root)
    if not entries:
        print("no sources found under src/core", file=sys.stderr)
        return 2
    text = render(entries)
    output = os.path.join(root, arguments.output)
    if arguments.check:
        if not os.path.exists(output):
            print("missing " + output, file=sys.stderr)
            return 1
        with open(output, "r", encoding="utf-8") as handle:
            if handle.read() != text:
                print("out of date: " + output, file=sys.stderr)
                return 1
        print("up to date: %d sources" % len(entries))
        return 0
    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote %s (%d sources)" % (output, len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
